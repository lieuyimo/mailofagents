// Command docs-stats generates the volatile statistics that belong in docs.
// Hand-maintained line counts drift immediately; the manifest lists the
// modules and their roles, this command supplies the current line counts, and
// `-check` (run in CI) fails when the checked-in block is stale.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	beginMarker = "<!-- BEGIN GENERATED frontend-modules -->"
	endMarker   = "<!-- END GENERATED frontend-modules -->"
)

type row struct {
	file  string
	role  string
	lines int
}

func main() {
	doc := flag.String("doc", "docs/overview-handover.md", "document to update")
	manifest := flag.String("manifest", "docs/frontend-modules.tsv", "module manifest")
	static := flag.String("static", "internal/server/static", "frontend directory")
	write := flag.Bool("write", false, "rewrite the generated block")
	check := flag.Bool("check", false, "fail if the generated block is stale")
	flag.Parse()

	rows, err := readRows(*manifest, *static)
	if err != nil {
		fail(err)
	}
	block := render(rows)
	if !*write && !*check {
		fmt.Print(block)
		return
	}
	raw, err := os.ReadFile(*doc)
	if err != nil {
		fail(err)
	}
	updated, err := replaceBlock(string(raw), block)
	if err != nil {
		fail(err)
	}
	if *check {
		if updated != string(raw) {
			fail(fmt.Errorf("%s is stale; run `go run ./cmd/docs-stats -write`", *doc))
		}
		fmt.Println("DOCS STATS: PASS (generated blocks are current)")
		return
	}
	if err := os.WriteFile(*doc, []byte(updated), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("updated %s (%d modules)\n", *doc, len(rows))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "docs-stats:", err)
	os.Exit(1)
}

func readRows(manifest, static string) ([]row, error) {
	raw, err := os.ReadFile(manifest)
	if err != nil {
		return nil, err
	}
	var rows []row
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, "\t", 2)
		if len(parts) != 2 {
			return nil, fmt.Errorf("%s: expected file<TAB>role, got %q", manifest, line)
		}
		n, err := countLines(filepath.Join(static, parts[0]))
		if err != nil {
			return nil, err
		}
		rows = append(rows, row{file: parts[0], role: parts[1], lines: n})
	}
	return rows, nil
}

func countLines(path string) (int, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	n := bytes.Count(raw, []byte("\n"))
	if len(raw) > 0 && raw[len(raw)-1] != '\n' {
		n++
	}
	return n, nil
}

func render(rows []row) string {
	var b strings.Builder
	b.WriteString(beginMarker + "\n")
	b.WriteString("<!-- Generated by `go run ./cmd/docs-stats -write`; do not edit by hand. -->\n")
	b.WriteString("| 模块 | 行数 | 职责 |\n")
	b.WriteString("|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %d | %s |\n", r.file, r.lines, r.role)
	}
	b.WriteString(endMarker)
	return b.String()
}

func replaceBlock(doc, block string) (string, error) {
	start := strings.Index(doc, beginMarker)
	end := strings.Index(doc, endMarker)
	if start < 0 || end < 0 || end < start {
		return "", fmt.Errorf("generated block markers not found")
	}
	return doc[:start] + block + doc[end+len(endMarker):], nil
}
